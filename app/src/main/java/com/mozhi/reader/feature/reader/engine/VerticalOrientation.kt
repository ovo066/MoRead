/**
 * Unicode vertical presentation forms (UnicodeData `<vertical>` decompositions, extended to the
 * fullwidth `<wide>` variants Chinese text actually uses). They are the fallback when a font has
 * no `vert` alternate: U+FE10 ︐ is a comma already placed in the upper right of its cell, U+FE41 ﹁
 * a corner bracket already turned for a column, and so on.
 */
object VerticalForms {
    fun of(text: String): String? {
        if (text.isEmpty() || Character.charCount(text.codePointAt(0)) != text.length) return null
        return FORMS[text.codePointAt(0)]?.let { String(Character.toChars(it)) }
    }

    private val FORMS: Map<Int, Int> = mapOf(
