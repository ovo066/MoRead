/**
 * Unicode UAX #50 `Vertical_Orientation`, generated from the Unicode Character Database
 * `VerticalOrientation.txt` (VerticalOrientation-18.0.0.txt). Only the non-`R` ranges are kept;
 * every code point outside them is `R` (drawn sideways in vertical text).
 *
 * Browsers use exactly this property to decide which characters stay upright in
 * `text-orientation: mixed`; reusing the published data keeps vertical EPUBs consistent with
 * them instead of inventing a CJK heuristic.
 */
enum class VerticalOrientation {
    /** Upright, same glyph as horizontal. */
    U,
    /** Upright; a vertical alternate (`vert` feature) moves it, e.g. 。，、 to the upper right. */
    TU,
    /** Upright with a rotated vertical alternate; rotate sideways when the font has none. */
    TR,
    /** Rotated 90° clockwise, like Latin letters. */
    R;

    companion object {
        fun of(codePoint: Int): VerticalOrientation {
            var low = 0
            var high = RANGES.size / 3 - 1
            while (low <= high) {
                val mid = (low + high) ushr 1
                val start = RANGES[mid * 3]
                val end = RANGES[mid * 3 + 1]
                when {
                    codePoint < start -> high = mid - 1
                    codePoint > end -> low = mid + 1
                    else -> return when (RANGES[mid * 3 + 2]) {
                        0 -> U
                        1 -> TU
                        else -> TR
                    }
                }
            }
            return R
        }

